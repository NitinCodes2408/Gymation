/**
 * GymTrack AI - Biometric Integration Types
 * 
 * Defines data structures and contracts for:
 * - Device configuration & credentials
 * - TCP/IP network reachability diagnostics
 * - Bridge-to-cloud transaction payloads
 * - Biometric hardware state representation
 * - Safe Member ID ↔ Biometric User ID mapping
 */

export type DeviceConnectionType = "TCP_IP" | "RS485" | "USB";

export type DeviceStatus = "ONLINE" | "OFFLINE" | "UNCONFIGURED" | "CONNECTING" | "ERROR";

export interface BiometricDeviceConfig {
  /** IP address assigned to the biometric terminal on the local LAN (e.g., "192.168.1.200") */
  deviceIp: string;
  /** TCP port for device communication (default for eSSL/ZK devices is typically 4370) */
  devicePort: number;
  /** Internal Machine/Device ID configured on the device (default is usually 1) */
  deviceId: number;
  /** Device Serial Number (if applicable/available on device label or system info) */
  deviceSerial?: string;
  /** Communication password / Comm Key (default 0 or empty if not set on the device) */
  commKey?: number | string;
  /** Timeout in milliseconds for TCP socket connection attempts (default 5000ms) */
  timeoutMs?: number;
}

export interface BiometricDiagnosticResult {
  /** Timestamp when diagnostic check was executed (ISO string) */
  timestamp: string;
  /** Configured device IP address (masked or sanitized for frontend safety if needed) */
  configuredIp: string;
  /** Configured TCP port */
  configuredPort: number;
  /** Configured Device ID */
  configuredDeviceId: number;
  /** True if essential configuration (IP & Port) is missing */
  isConfigMissing: boolean;
  /** Detailed error message if configuration is incomplete */
  configError?: string;
  /** True if TCP connection to device IP:Port succeeded */
  tcpSuccess: boolean;
  /** True if the connection timed out */
  isTimeout: boolean;
  /** Round-trip latency in milliseconds if connection was successful */
  latencyMs?: number;
  /** Network or socket error message if failed */
  errorMessage?: string;
  /** Low-level socket error code (e.g. "ETIMEDOUT", "ECONNREFUSED", "EHOSTUNREACH") */
  errorCode?: string;
  /** Human-readable status summary */
  summary: string;
}

export interface BiometricDeviceUser {
  /** Machine internal index */
  uid: number;
  /** Authoritative biometric User ID stored on the terminal (e.g. "19", "6", "1") */
  userId: string;
  /** Optional reference name stored on the device label */
  name?: string;
  /** Card number if configured */
  cardno?: number;
  /** Current mapping status in active gym */
  mappingStatus?: "MAPPED" | "UNMAPPED";
  /** Mapped GymTrack member ID if assigned */
  mappedMemberId?: string;
  /** Mapped GymTrack member name if assigned */
  mappedMemberName?: string;
}

export interface BiometricLogTransaction {
  /** Unique log transaction ID or generated ID */
  transactionId: string;
  /** User/Pin/Enrollment ID stored on the biometric terminal (e.g., "19") */
  deviceUserId: string;
  /** Corresponding GymTrack AI Member ID (e.g., "M-1019") once resolved */
  memberId?: string;
  /** Check-in timestamp from the biometric machine (ISO string or YYYY-MM-DD HH:mm:ss) */
  recordTime: string;
  /** Verification mode: 1 = Fingerprint, 2 = Pin, 3 = Card, 4 = Face, etc. */
  verifyMode?: number;
  /** In/Out state: 0 = Check-in, 1 = Check-out, etc. */
  inOutState?: number;
  /** Machine Number/ID that generated the log */
  deviceId: number;
}

export interface BiometricSyncPayload {
  /** Gym ID associated with this biometric sync */
  gymId: string;
  /** Device identifier */
  deviceSerial?: string;
  /** Array of verified attendance transactions from the terminal */
  transactions: BiometricLogTransaction[];
  /** Timestamp when the sync payload was generated by the local bridge */
  syncedAt: string;
  /** Security token / bridge secret for authenticating the local bridge */
  bridgeSecret: string;
}

export interface BiometricSyncResult {
  success: boolean;
  syncedCount: number;
  ignoredCount: number;
  errors?: string[];
  message: string;
}
